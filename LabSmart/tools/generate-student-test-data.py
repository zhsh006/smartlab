def dots(c,values,x,y,w,h,ylabel,ymax=None):
    ymax=ymax or max(max(v) for v in values)*1.25
    c.setStrokeColorRGB(.2,.25,.28);c.setLineWidth(1)
    c.line(x,y,x+w,y);c.line(x,y,x,y+h)
    c.setFont('Helvetica',10)
    for i in range(5):
        v=ymax*i/4;yy=y+h*i/4
        c.setStrokeColorRGB(.90,.92,.93);c.line(x,yy,x+w,yy)
        c.setFillColorRGB(.25,.3,.33);c.drawRightString(x-9,yy-3,f'{v:.2g}')
    colors=[(.19,.44,.49),(.76,.32,.22)]
    for k,vs in enumerate(values):
        xx=x+w*(k+1)/3;mean=float(np.mean(vs));sd=float(np.std(vs,ddof=1)) if len(vs)>1 else 0
        c.setStrokeColorRGB(*colors[k]);c.setFillColorRGB(*colors[k]);c.setLineWidth(2)
        c.line(xx-22,y+mean/ymax*h,xx+22,y+mean/ymax*h)
        c.line(xx,y+(mean-sd)/ymax*h,xx,y+(mean+sd)/ymax*h)
        for sign in [-1,1]:c.line(xx-7,y+(mean+sign*sd)/ymax*h,xx+7,y+(mean+sign*sd)/ymax*h)
        for j,v in enumerate(vs):c.circle(xx+(j-(len(vs)-1)/2)*11,y+float(v)/ymax*h,4,fill=1,stroke=0)
        c.setFont('Helvetica',11);c.setFillColorRGB(.2,.25,.28);c.drawCentredString(xx,y-22,['Control','Treatment'][k])
    c.saveState();c.translate(x-49,y+h/2);c.rotate(90);c.setFont('Helvetica',11);c.drawCentredString(0,0,ylabel);c.restoreState()

